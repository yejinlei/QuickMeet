//! 各 codec 的具体实现。
//!
//! 默认实现全部是**确定性、无损、纯 Rust** 的载荷封装（无系统库依赖），
//! 这样 `cargo test` 在任何机器上都能得到完全一致的字节 —— 这是"可复现
//! 收发验证"的前提。真实编解码器通过 cargo 特性接入：
//!
//! | 特性          | 编解码器                | 前置条件                       |
//! | ------------- | ----------------------- | ------------------------------ |
//! | `native-opus` | opus-rs / opusic-sys    | 需要 C 编译器（自带 C 源码）   |
//! | `native-h264` | OpenH264                | 需要 C 编译器 + 下载 OpenH264 源码 |
//! | `native-vp8`  | libvpx（FFI）           | 本机需安装 libvpx              |

pub mod h264;
pub mod opus;
pub mod vp8;
